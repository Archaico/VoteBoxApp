#!/usr/bin/env node
// scripts/gen-locales-index.js
//
// Regenerates src/i18n/locales/index.ts from the folders in src/i18n/locales/
// (one folder per language, one JSON per namespace). Run after adding or
// removing a language: node scripts/gen-locales-index.js

const fs = require('fs');
const path = require('path');

const LOCALES = path.join(__dirname, '..', 'src', 'i18n', 'locales');
const langs = fs.readdirSync(LOCALES)
  .filter(d => fs.statSync(path.join(LOCALES, d)).isDirectory())
  .sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));
const namespaces = fs.readdirSync(path.join(LOCALES, 'en'))
  .filter(f => f.endsWith('.json'))
  .map(f => f.replace('.json', ''));

const ident = (lang, ns) => `${lang.replace(/-/g, '_')}_${ns}`;

const lines = [
  '// src/i18n/locales/index.ts',
  '//',
  '// GENERATED by scripts/gen-locales-index.js — do not edit by hand.',
  '// One JSON file per namespace per language: ./<lang>/<namespace>.json.',
  '// English is the source of truth.',
  '',
  ...langs.flatMap(lang => namespaces.map(ns => `import ${ident(lang, ns)} from './${lang}/${ns}.json';`)),
  '',
  `export const NAMESPACES = [${namespaces.map(ns => `'${ns}'`).join(', ')}] as const;`,
  '',
  'export const resources = {',
  ...langs.map(lang => `  '${lang}': { ${namespaces.map(ns => `${ns}: ${ident(lang, ns)}`).join(', ')} },`),
  '};',
  '',
];

fs.writeFileSync(path.join(LOCALES, 'index.ts'), lines.join('\n'));
console.log(`Wrote ${langs.length} language(s) × ${namespaces.length} namespaces: ${langs.join(', ')}`);
